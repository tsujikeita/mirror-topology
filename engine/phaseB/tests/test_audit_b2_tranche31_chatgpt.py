def test_e1_required_parent_tech_is_not_exempted(base,tmp_path,monkeypatch):
    f=copy.deepcopy(base);f['cases']=family_cases(f['reg'],f['man'],'E1')
    original=orch._stage_selection
    def failure(fam,t1,t2):
        sel=original(fam,t1,t2)
        if fam.family=='E1' and len(fam.configs)==3:
            sel['technical']=True;sel['N0']['precision']['state']='technical_fail'
        return sel
    monkeypatch.setattr(orch,'_stage_selection',failure)
    r,a=run(f,tmp_path)
    assert r.families['E1']['status']=='technical_fail'
    assert r.calibration['support']['summary']['status']=='technical_fail'
    for k,c in r.cases.items():
        tr=StageTransition(**r.families['E1']['transitions'][c['size_id']])
        rec=resolve_transition_archive(a,tr,ArchiveRef(**c['result_ref']))
        assert tr.phase=='technical_fail' and rec['decision']['technical_status']=='technical_fail'

