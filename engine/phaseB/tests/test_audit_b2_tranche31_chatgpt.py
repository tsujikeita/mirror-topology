def test_pseudo_values_recover_bit_exactly_with_matching_array_hashes(base,tmp_path):
    f=copy.deepcopy(base);x=np.array([80.125,81.375,83.625]);y=np.array([400.0625,401.5625,412.5])
    r,a=run(f,tmp_path,pseudo_T1=x,pseudo_T2=y)
    persisted=a.get(ArchiveRef(**r.binding['run_manifest_ref']))['thresholds']['pseudo']
    assert persisted['dtype']=='float64' and persisted['n']==3 and persisted['shape']==[3]
    for name,expected in [('T1',x),('T2',y)]:
        recovered=np.asarray(persisted[name],dtype=np.float64)
        assert recovered.tobytes()==expected.tobytes()
        assert hashlib.sha256(recovered.tobytes()).hexdigest()==persisted['sha256_'+name]

