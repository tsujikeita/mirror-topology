def test_normal_reopened_run_resolves_position_parent_and_diagnostic_links(normal):
    f,r,old=normal;a=Archive(old.root)
    body=a.get(ArchiveRef(**r.binding['run_manifest_ref']));restored=RunManifest(**body)
    for k,c in restored.cases.items():
        tr=StageTransition(**restored.families[c['family']]['transitions'][c['size_id']])
        rec=resolve_transition_archive(a,tr,ArchiveRef(**c['result_ref']))
        parent_key=rec['evidence']['parent_family_result']
        p=a.get(ArchiveRef(**restored.archive_refs[parent_key]))
        d=a.get(ArchiveRef(**rec['evidence']['diagnostic_ref']))
        assert p['family']==rec['family']==d['family']
        assert d['size_id']==rec['size_id']
        assert rec['decision']['technical_status']==p['decision']['technical_status']
    assert restored.payload_sha()==r.payload_sha()==r.binding['run_manifest_sha256']
    assert a.verify_all()['ok']

