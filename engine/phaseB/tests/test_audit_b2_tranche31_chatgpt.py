def run(f,path,**kw):
    opts=dict(t_target=(80.,400.),pseudo_T1=[80.],pseudo_T2=[400.],mode='smoke');opts.update(kw)
    a=Archive(str(path));r=run_first_wave(f['reg'],f['man'],f['cases'],f['ctx'],f['ctx'].context_sha256,archive=a,**opts)
    return r,a

def parent_result(r,a,family='E7'):
    return a.get(ArchiveRef(**r.archive_refs['family_core:'+family]))

def source(r,a,key):return a.get(ArchiveRef(**r.cases[key]['result_ref']))

def assert_derivation(f,r,a,family='E7'):
    parent=parent_result(r,a,family)
    for key,(fm,fn,pmap) in f['cases'].items():
        if fm.family!=family:continue
        rec=source(r,a,key)
        assert rec['kind']=='case_position_record'
        assert rec['truths']==parent['truths']
        assert rec['precision']==parent['precision']
        assert rec['decision']['technical_status']==parent['decision']['technical_status']
        assert rec['decision']['display_label']==parent['decision']['display_label']
        assert rec['evidence']['parent_family_result']=='family_core:'+family
        if family=='E1':
            assert rec['evidence']['position_probabilities']=={}
            continue
        for eid,pos in pmap.items():
            p=rec['evidence']['position_probabilities'][pos];d=parent['per_config'][eid]
            assert p==dict(P=d['P_model'],hits=d['hits_M'],N=d['N'],precision=d['precision']['state'],stage=d['stage'])
            c=next(c for c in fm.configs if c.evaluation_id==eid);n=p['N']
            hits=int(np.count_nonzero((c.T1_model[:n]<=80.)&(c.T2_model[:n]<=400.)))
            assert hits==p['hits'] and p['P']==hits/n

